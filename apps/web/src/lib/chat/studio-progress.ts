/**
 * How a studio run's progress reads in its chat: a sentence for each step it recorded, its state,
 * and the image to show of it, from its events and, once it has been read, from the run itself.
 *
 * The run's own record wins over its events once it has ended: a run whose workflow could not be
 * started is recorded as failed without ever recording an event. The image is named by ids only,
 * from the events or the record, and its address is built by `lib/studio/image-src.ts`. The first
 * step that makes an image names its asset, so the newest image is shown while the run is going. A
 * reason is the code's sentence; the screen shows it as text.
 *
 * Display only.
 */

import type { StudioRun, StudioRunStatus } from "@/lib/api/types";
import { assetImageAlt } from "@/lib/studio/image-src";

import type { StudioRunView, StudioStage } from "./events";

export type StudioProgressStatus = {
  state: StudioRunStatus;
  /** The asset its images belong to, once a step or its record named it; none for a run that failed. */
  assetId: string | null;
  reason: string | null;
};

export function studioProgressStatus(view: StudioRunView, run: StudioRun | undefined): StudioProgressStatus {
  if (run?.status === "failed") return { state: "failed", assetId: null, reason: run.error ?? view.reason };
  if (run?.status === "succeeded" || run?.status === "needs_review") {
    return { state: run.status, assetId: run.final_asset_id ?? view.assetId, reason: null };
  }
  if (view.status === "finished") {
    return { state: view.needsReview === true ? "needs_review" : "succeeded", assetId: view.assetId, reason: null };
  }
  if (view.status === "failed") return { state: "failed", assetId: null, reason: view.reason };
  const queued = run?.status === "queued" && view.stages.length === 0;
  return { state: queued ? "queued" : "running", assetId: view.assetId, reason: null };
}

export type Candidate = {
  assetId: string;
  versionId: string;
  /** Whether it is the image the run ended with, rather than the newest one a step made. */
  final: boolean;
};

/** The image to show of the run: the one it ended with, or else the newest one a step made, once the asset is known. */
export function latestCandidate(view: StudioRunView, status: StudioProgressStatus): Candidate | null {
  const versionId = view.finalVersionId ?? view.latestVersionId;
  if (status.assetId === null || versionId === null) return null;
  return { assetId: status.assetId, versionId, final: view.finalVersionId !== null };
}

/** What the image is, for someone who cannot see it; the platform comes with the run's record. */
export function candidateAlt(platform: string | undefined): string {
  return platform === undefined ? "Image made by the studio run" : assetImageAlt(platform);
}

/** The sentence that ends a run's card once it has its image. */
export function studioOutcomeText(status: StudioProgressStatus): string | null {
  switch (status.state) {
    case "succeeded":
      return "Done: the image waits in the Studio library for your decision.";
    case "needs_review":
      return "Stopped at its limits before a candidate passed every check: the best one waits in the Studio library for your review.";
    default:
      return null;
  }
}

const TECHNIQUES = new Map<string, string>([
  ["generated", "an image generated by the image model"],
  ["html_reference", "a layout in HTML that the image model generates from"],
  ["background_overlay", "a generated background with words set in code"],
  ["composed", "an image composed in code"],
]);

/** A technique as the end of a sentence; one the dashboard does not know yet is shown by its name. */
export function techniquePhrase(technique: string): string {
  return TECHNIQUES.get(technique) ?? technique;
}

// What an operation did, and what it tried to do.
const OPERATIONS = new Map<string, { done: string; tried: string }>([
  ["generate_image", { done: "Generated an image", tried: "generate an image" }],
  ["edit_image", { done: "Edited an image", tried: "edit an image" }],
  ["render_html", { done: "Rendered an image from HTML", tried: "render an image from HTML" }],
  ["run_python", { done: "Drew an image in code", tried: "draw an image in code" }],
]);

const CHECK_FAILURES = new Map<string, string>([
  ["size", "the wrong size"],
  ["format", "the wrong file format"],
  ["bytes", "too large a file"],
  ["unreadable", "a file that could not be read as an image"],
  ["copy", "words that do not read as asked"],
  ["copy_unread", "words that could not be read back"],
  ["no_candidate", "no candidate"],
]);

const CRITERIA = new Map<string, string>([
  ["legibility", "legibility"],
  ["copy_rendered", "the words as drawn"],
  ["brand_fit", "fit with the brand"],
  ["artifacts", "visual flaws"],
  ["composition", "composition"],
  ["risky_content", "risky content"],
]);

/** What one step did, as a line of the run's card. */
export function studioStageText(stage: StudioStage): string {
  switch (stage.kind) {
    case "briefed":
      return `Planned the image: ${techniquePhrase(stage.technique)}`;
    case "produced": {
      const operation = OPERATIONS.get(stage.operation);
      const round = inRound(stage.round);
      if (stage.ok) return `${operation?.done ?? `Ran ${stage.operation}`}${round}`;
      return `Could not ${operation?.tried ?? `run ${stage.operation}`}${round}`;
    }
    case "checked":
      return stage.passed
        ? "Checked the image: size, format and words are right"
        : `Checked the image: ${listed(stage.failures.map((key) => CHECK_FAILURES.get(key) ?? key))}`;
    case "verified":
      return stage.passed
        ? "Reviewed by the verifier: it passed"
        : `Reviewed by the verifier: failed on ${listed(stage.failed.map((key) => CRITERIA.get(key) ?? key))}`;
    case "technique_switched":
      return `Switched to ${techniquePhrase(stage.to)}`;
    case "edit_planned": {
      const steps = `${stage.steps} ${stage.steps === 1 ? "step" : "steps"}`;
      return stage.round === null ? `Planned the edits: ${steps}` : `Planned the edits of round ${stage.round}: ${steps}`;
    }
    case "finalized":
      return stage.round === null ? "Chose the final image" : `Chose the image of round ${stage.round}`;
    case "escalated":
      return stage.reason.trim() === "" ? "Stopped before a candidate passed" : `Stopped: ${stage.reason}`;
  }
}

function inRound(round: number | null): string {
  return round === null ? "" : ` (round ${round})`;
}

/** "a", "a and b", "a, b and c"; for none, which a failed check should not have, that something did not pass. */
function listed(items: readonly string[]): string {
  if (items.length === 0) return "something did not pass";
  if (items.length === 1) return items[0];
  return `${items.slice(0, -1).join(", ")} and ${items.at(-1)}`;
}
