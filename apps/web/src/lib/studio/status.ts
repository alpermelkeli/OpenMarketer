/**
 * How the studio's runs and assets are shown: a state in words with a tone, the platform an
 * image is for, how a version was made, and what it cost or weighs. Display only: whether a
 * run is done and whether an asset may be decided on is the server's to say.
 */

import { QUEUED_TOO_LONG_MS, runElapsedMs, type Tone } from "@/lib/analysis/run-status";
import type { MediaAssetStatus, Platform, StudioRun, StudioRunStatus } from "@/lib/api/types";

type StatusDisplay = { label: string; tone: Tone };

const RUN_STATUS: Record<StudioRunStatus, StatusDisplay> = {
  queued: { label: "Queued", tone: "neutral" },
  running: { label: "Making the image", tone: "progress" },
  succeeded: { label: "Finished", tone: "success" },
  needs_review: { label: "Needs your review", tone: "warning" },
  failed: { label: "Failed", tone: "danger" },
};

export function studioRunStatusDisplay(status: StudioRunStatus): StatusDisplay {
  return RUN_STATUS[status];
}

/** A run that has ended never changes again, so it is no longer polled. */
export function isStudioRunFinished(run: Pick<StudioRun, "status">): boolean {
  return run.status === "succeeded" || run.status === "needs_review" || run.status === "failed";
}

/** After a while in the queue, the likeliest reason is that no worker is running. */
export function isStudioRunWaitingForWorker(
  run: Pick<StudioRun, "status" | "created_at" | "finished_at">,
  now: number,
): boolean {
  return run.status === "queued" && runElapsedMs(run, now) >= QUEUED_TOO_LONG_MS;
}

const ASSET_STATUS: Record<MediaAssetStatus, StatusDisplay> = {
  draft: { label: "Draft", tone: "warning" },
  accepted: { label: "Accepted", tone: "success" },
  rejected: { label: "Rejected", tone: "danger" },
};

export function assetStatusDisplay(status: MediaAssetStatus): StatusDisplay {
  return ASSET_STATUS[status];
}

const PLATFORMS: Record<Platform, string> = {
  instagram_post: "Instagram post",
  instagram_portrait: "Instagram portrait",
  instagram_story: "Instagram story",
  x_post: "X post",
  linkedin_post: "LinkedIn post",
  og_image: "Link preview (Open Graph)",
  app_store_screenshot: "App Store screenshot",
};

/** Every platform the studio makes images for, in the order a form offers them. */
export const PLATFORM_OPTIONS: readonly { value: Platform; label: string }[] = (
  Object.keys(PLATFORMS) as Platform[]
).map((value) => ({ value, label: PLATFORMS[value] }));

/** The platform's name; a slug the dashboard does not know yet is shown as it came. */
export function platformLabel(platform: string): string {
  return Object.hasOwn(PLATFORMS, platform) ? PLATFORMS[platform as Platform] : platform;
}

// A map, so that a technique the studio adds later is shown by its name instead of breaking the page.
const TECHNIQUES = new Map<string, string>([
  ["generated", "Generated by the image model"],
  ["html_reference", "Laid out in HTML, then generated from the layout"],
  ["background_overlay", "Generated background, words set by code"],
  ["composed", "Composed by code"],
]);

export function techniqueLabel(technique: string): string {
  return TECHNIQUES.get(technique) ?? technique;
}

const REQUESTED_BY = new Map<string, string>([
  ["person", "a person"],
  ["orchestrator", "the orchestrator chat"],
  ["run", "another run"],
]);

export function requestedByLabel(requestedBy: string): string {
  return REQUESTED_BY.get(requestedBy) ?? requestedBy;
}

const SMALL_COST = new Intl.NumberFormat("en", {
  style: "currency",
  currency: "USD",
  minimumFractionDigits: 2,
  maximumFractionDigits: 4,
});
const COST = new Intl.NumberFormat("en", { style: "currency", currency: "USD" });

/** "$0.04", "$0.0123", "$1.50": a cent is not enough for an image that cost a fraction of one. */
export function formatCost(usd: number): string {
  return Math.abs(usd) < 1 ? SMALL_COST.format(usd) : COST.format(usd);
}

/** "812 bytes", "412 KB", "1.2 MB". */
export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} bytes`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}
