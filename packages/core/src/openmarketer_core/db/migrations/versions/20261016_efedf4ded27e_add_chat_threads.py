def _backfill_threads(bind: sa.engine.Connection) -> None:
    """Give every project that already has messages one thread, and point its messages at it."""
    project_ids = bind.execute(sa.text("SELECT DISTINCT project_id FROM chat_message")).scalars()
    for project_id in project_ids:
        title, _ = bind.execute(
            sa.text(
                "SELECT content, created_at FROM chat_message"
                " WHERE project_id = :project_id"
                " ORDER BY created_at, id"
                " LIMIT 1"
            ),
            {"project_id": project_id},
        ).one()
