def _title_of(content: str) -> str:
    first_line = (content.splitlines() or [""])[0].strip()
    if len(first_line) > TITLE_MAX_LENGTH:
        clipped = first_line[:TITLE_MAX_LENGTH]
        boundary = clipped.rfind(" ")
        first_line = clipped[:boundary].rstrip() if boundary > 0 else clipped
    return first_line or FALLBACK_TITLE
